SELECT
    {{ format_name('SURNAME') }}                AS LAST_NAME,
    {{ format_date('DATE_HIRED') }}              AS HIRED_DATE,
    {{ format_name('DEPARTMENT') }}              AS DEPARTMENT,
    {{ format_name('FIRST_NAME') }}              AS FIRST_NAME,
    TRIM(EMPLOYEE_NO)                            AS EMPLOYEE_NO,
    {{ format_name('MIDDLE_NAME') }}             AS MIDDLE_NAME,
    TRIM(RDO_APPROVED)                           AS RDO_APPROVED,
    TRIM(WORK_PATTERN)                           AS WORK_PATTERN,
    TRIM(CONTRACT_HOURS)                         AS CONTRACT_HOURS,
    {{ format_name('PREFERRED_NAME') }}          AS PREF_NAME,
    TRIM(EMPLOYMENT_TYPE)                        AS EMPLOYMENT_TYPE,
    {{ format_name('CURRENT_POSITION') }}        AS CURRENT_POSITION,
    {{ format_date('TERMINATION_DATE') }}        AS TERMINATION_DATE,
    {{ format_date('PROBATION_END_DATE') }}      AS PROBATION_END_DATE,
    TRIM(TIL_LEAVE_APPROVED)                     AS TIL_LEAVE_APPROVED,
    LOWER(TRIM(WORK_EMAIL_ADDRESS))              AS WORK_EMAIL,
    {{ format_date('FIXED_TERM_END_DATE') }}     AS FIXED_TERM_END_DATE,
    TRIM(RDO_BALANCE_ACCRUED)                    AS RDO_BALANCE_ACCRUED,
    {{ format_name('REPORTS_TO_POSITION_') }}    AS REPORTS_TO_POSITION,
    TRIM(ANNUAL_LEAVE_APPROVED)                  AS ANNUAL_LEAVE_APPROVED,
    {{ format_date('FIXED_TERM_START_DATE') }}   AS FIXED_TERM_START_DATE,
    TRIM(PERSONAL_LEAVE_APPROVED)                AS PERSONAL_LEAVE_APPROVED,
    TRIM(POSITION_ALLOCATED_HOURS)               AS POSITION_ALLOCATED_HOURS,
    {{ format_name('REPORTS_TO_MANAGER_NAME_') }} AS REPORTS_TO_MANAGER_NAME,
    TRIM(TIL_LEAVE_BALANCE_ACCRUED)              AS TIL_LEAVE_BALANCE_ACCRUED,
    TRIM(ANNUAL_LEAVE_BALANCE_ACCRUED)           AS ANNUAL_LEAVE_BALANCE_ACCRUED,
    TRIM(PERSONAL_LEAVE_BALANCE_ACCRUED)         AS PERSONAL_LEAVE_BALANCE_ACCRUED,
    TRIM(TERMINATION_REASON_FOR_LEAVING)         AS TERMINATION_REASON,
    TRIM(USED_DEFINED_PURCHASED_LEAVE_ACCRUED)   AS USED_DEFINED_PURCHASED_LEAVE_ACCRUED,
    TRIM(USER_DEFINED_PURCHASED_LEAVE_APPROVED)  AS USER_DEFINED_PURCHASED_LEAVE_APPROVED,

    _AIRBYTE_EXTRACTED_AT                         AS AIRBYTE_EXTRACTED_TS

FROM {{ ref('HIST_CONNX_EMPLOYEE_DATA') }}
WHERE dbt_valid_to = TO_DATE('9999-12-31')