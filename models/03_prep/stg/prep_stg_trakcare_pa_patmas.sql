    NULLIF(CAST(PAPMI_ROWID AS VARCHAR), 'NULL')    AS PATIENT_ID,
    NULLIF(PAPMI_NO, 'NULL')                         AS PATIENT_NO,
    NULLIF(INITCAP(TRIM(PAPMI_NAME)), 'NULL')        AS LAST_NAME,
    NULLIF(INITCAP(TRIM(PAPMI_NAME2)), 'NULL')       AS FIRST_NAME,
    NULLIF(TRIM(PAPMI_NAME3), 'NULL')                AS MIDDLE_NAME,
    NULLIF(TRIM(PAPMI_ALIAS), 'NULL')                AS ALIAS,
    PAPMI_DOB                                        AS DOB,
    PAPMI_SEX_DR                                     AS SEX_DR,
    PAPMI_PAPER_DR                                   AS PERSON_DR,
    NULLIF(LOWER(TRIM(PAPMI_EMAIL)), 'null')         AS EMAIL,
    NULLIF(TRIM(PAPMI_MOBPHONE), 'NULL')             AS MOBILE_PHONE,
    NULLIF(TRIM(PAPMI_SECONDPHONE), 'NULL')          AS HOME_PHONE,
