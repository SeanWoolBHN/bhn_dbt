    NULLIF(TRIM(PAPMI_MEDICARESTRING), 'NULL')       AS MEDICARE_STRING,
    PAPMI_MEDICAREEXPDATE                            AS MEDICARE_EXPIRY_DATE,
    NULLIF(TRIM(PAPMI_DVANUMBER), 'NULL')            AS DVA_NO,
    PAPMI_CARDTYPE_DR                                AS CARD_TYPE_DR,
    NULLIF(TRIM(PAPMI_CONCESSIONCARDNO), 'NULL')     AS CONCESSION_CARD_NO,
    PAPMI_CONCESSIONCARDEXPDATE                      AS CONCESSION_CARD_EXPIRY_DATE,
    NULLIF(TRIM(PAPMI_HEALTHFUNDNO), 'NULL')         AS HEALTH_FUND_NO,
    PAPMI_TITLE_DR                                   AS TITLE_DR,
    PAPMI_PREFLANGUAGE_DR                            AS PREF_LANGUAGE_DR,
    PAPMI_COUNTRYOFBIRTH_DR                          AS BIRTH_COUNTRY_DR,
    PAPMI_INDIGSTAT_DR                               AS INDIGENOUS_STATUS_DR,
    PAPMI_PENSIONTYPE_DR                             AS PENSION_TYPE_DR,
    PAPMI_CT_REGION_DR                               AS REGION_DR,
    PAPMI_CT_PROVINCE_DR                             AS PROVINCE_DR,
    PAPMI_CITYAREA_DR                                AS CITY_AREA_DR,
    PAPMI_CITYBIRTH_DR                               AS BIRTH_CITY_DR,
    PAPMI_CT_HCA_DR                                  AS HCA_DR,
    NULLIF(TRIM(PAPMI_ACTIVE), 'NULL')               AS ACTIVE,
    NULLIF(TRIM(PAPMI_DECEASED), 'NULL')             AS DECEASED,
    PAPMI_DECEASED_DATE                              AS DECEASED_DATE,
    NULLIF(TRIM(PAPMI_REMARK), 'NULL')               AS REMARK,
    NULLIF(TRIM(PAPMI_ALLERGY), 'NULL')              AS ALLERGY,
    NULLIF(TRIM(PAPMI_GPTEXT), 'NULL')               AS GP_TEXT,
    NULLIF(TRIM(PAPMI_GPORGADDRESS), 'NULL')         AS GP_ORG_ADDRESS,
    PAPMI_REFDOC_DR                                  AS REF_DOC_DR,
    PAPMI_DENTIST_DR                                 AS DENTIST_DR,
    PAPMI_DENTISTCLINIC_DR                           AS DENTIST_CLINIC_DR,
    PAPMI_AUXINSTYPE_DR                              AS AUX_INS_TYPE_DR,
    PAPMI_TRACESTATUS_DR                             AS TRACE_STATUS_DR,
    PAPMI_MEDICARESUFFIX_DR                          AS MEDICARE_SUFFIX_DR,
    PAPMI_MEDICARECARDTYPE_DR                        AS MEDICARE_CARD_TYPE_DR,
    PAPMI_MOTHER_DR                                  AS MOTHER_DR,
    PAPMI_MOTHER1_DR                                 AS MOTHER_1_DR,
    NULLIF(TRIM(PAPMI_BLACKLIST), 'NULL')            AS BLACKLIST,
    NULLIF(TRIM(PAPMI_VIPFLAG), 'NULL')              AS VIP_FLAG,
    NULLIF(TRIM(PAPMI_CHCPATIENT), 'NULL')           AS CHC_PATIENT,
    PAPMI_RESPONSIBLEFORPAYMENT                      AS RESPONSIBLE_FOR_PAYMENT,
    PAPMI_PATCATEGORY_DR                             AS PAT_CATEGORY_DR,
    PAPMI_LANGPRIM_DR                                AS LANG_PRIM_DR,
    PAPMI_USERUPDATE                                 AS USER_UPDATE,
    PAPMI_PAYORVERIFIEDDATE                          AS PAYOR_VERIFIED_DATE,
    PAPMI_HEALTHCARDEXPIRYDATE                       AS HEALTH_CARD_EXPIRY_DATE,
    PAPMI_SAFETYNETCARDEXPDATE                       AS SAFETY_NET_CARD_EXPIRY_DATE,
    PAPMI_CONCESSIONVERIFIEDDATE                     AS CONCESSION_VERIFIED_DATE,
    PAPMI_EMAILVALIDATIONSTATUS_DR                   AS EMAIL_VALIDATION_STATUS_DR,
    NULLIF(TRIM(PAPMI_REQUIREASSISTANCEMEAL), 'NULL') AS REQUIRE_ASSISTANCE_MEAL,
    NULLIF(TRIM(PAPMI_REQUIREASSISTANCEMENU), 'NULL') AS REQUIRE_ASSISTANCE_MENU,

    _AIRBYTE_EXTRACTED_AT                            AS AIRBYTE_EXTRACTED_TS

FROM {{ ref('HIST_TRAKCARE_PA_PATMAS') }}
WHERE dbt_valid_to = TO_DATE('9999-12-31')